import { test, expect } from "./fixtures";
import type { ElectronApi } from "../../../shared/electron-api";

test("real preload connects to main and the Agent utility process", async ({ desktop }) => {
  const { app, page } = desktop;
  expect(await app.evaluate(({ app }) => app.getPath("userData"))).toContain("mozi-e2e-");
  const state = await page.evaluate(() => (window as unknown as { electronAPI: ElectronApi }).electronAPI.window.getState());
  expect(state).toEqual({ isFullScreen: false });
  const settings = await page.evaluate(() => window.mozi!.agent.getModelSettings());
  expect(settings.ok).toBe(true);
  await expect(page.getByRole("textbox", { name: "消息内容" })).toBeVisible();
});

test("UI creates and renames a real session which survives an Electron restart", async ({ desktop }) => {
  let page = desktop.page;
  await page.getByRole("button", { name: "新建会话", exact: true }).click();
  await expect.poll(async () => page.evaluate(async () => {
    const result = await window.mozi!.agent.listSessions();
    return result.ok ? result.result.items.length : 0;
  })).toBe(1);
  await page.getByRole("button", { name: "切换会话", exact: true }).click();
  await page.getByRole("button", { name: "更多操作：新会话", exact: true }).click();
  await page.getByRole("menuitem", { name: "重命名", exact: true }).click();
  await page.getByRole("textbox", { name: "会话名称" }).fill("Electron 持久化验收");
  await page.getByRole("dialog", { name: "重命名会话" }).getByRole("button", { name: /保\s*存/ }).click();
  await expect(page.getByRole("button", { name: "更多操作：Electron 持久化验收", exact: true })).toBeVisible();
  await desktop.restart();
  page = desktop.page;
  await page.getByRole("button", { name: "切换会话", exact: true }).click();
  await expect(page.getByRole("button", { name: "更多操作：Electron 持久化验收", exact: true })).toBeVisible();
  const sessions = await page.evaluate(() => window.mozi!.agent.listSessions());
  expect(sessions.ok && sessions.result.items.map(item => item.title)).toEqual(["Electron 持久化验收"]);
});

test("preload opens a native monitor window with its own working bridge", async ({ desktop }) => {
  const { page, app } = desktop;
  const created = await page.evaluate(() => window.mozi!.agent.createSession({ clientOperationId: "monitor-e2e", title: "窗口验收" }));
  if (!created.ok) throw new Error(created.error.message);
  const opened = app.waitForEvent("window");
  expect(await page.evaluate(sessionId => (window as unknown as { electronAPI: ElectronApi }).electronAPI.window.openTokenMonitor({ sessionId }), created.result.sessionId)).toBe(true);
  const monitor = await opened;
  await expect(monitor).toHaveURL(/angetTokenMonitor\?sessionId=/);
  await expect(monitor.getByText("窗口验收", { exact: true })).toBeVisible();
  expect(await monitor.evaluate(() => (window as unknown as { electronAPI: ElectronApi }).electronAPI.window.getState())).toEqual({ isFullScreen: false });
  await monitor.evaluate(() => (window as unknown as { electronAPI: ElectronApi }).electronAPI.window.close());
  await expect.poll(() => app.windows().length).toBe(1);
  await expect(page.getByRole("button", { name: "新建会话", exact: true })).toBeEnabled();
});

test("projects contain sessions exclusively, survive restart and release sessions on deletion", async ({ desktop }) => {
  let page = desktop.page;
  await page.getByRole("button", { name: "新建会话", exact: true }).click();
  await page.getByRole("button", { name: "切换会话", exact: true }).click();
  await page.getByRole("button", { name: "＋ 创建项目", exact: true }).click();
  await page.getByRole("textbox", { name: "项目名称" }).fill("项目收纳验收");
  await page.getByRole("dialog", { name: "创建项目", exact: true }).getByRole("button", { name: /保\s*存/ }).click();
  await expect(page.getByRole("listbox", { name: "项目列表" }).getByRole("option", { name: /项目收纳验收/ })).toBeVisible();
  await page.getByRole("button", { name: "移动到项目", exact: true }).click();
  await page.getByRole("combobox", { name: "目标项目" }).click();
  await page.locator(".ant-select-item-option").filter({ hasText: "项目收纳验收" }).click();
  await page.getByRole("dialog", { name: "移动会话", exact: true }).getByRole("button", { name: /移\s*动/, exact: true }).click();
  await expect(page.getByRole("dialog", { name: "移动会话", exact: true })).not.toBeVisible();
  const projectList = page.getByRole("listbox", { name: "项目列表" });
  const sessionList = page.getByRole("listbox", { name: "匹配的会话" });
  await expect(sessionList.getByRole("option")).toHaveCount(0);
  await projectList.getByRole("option", { name: /项目收纳验收/ }).click();
  await expect(sessionList.getByRole("option")).toHaveCount(1);
  await page.getByRole("combobox", { name: "搜索会话标题" }).fill("新会话");
  await expect(page.getByRole("group", { name: "项目收纳验收", exact: true }).getByRole("option")).toHaveCount(1);
  await desktop.restart(); page = desktop.page;
  await page.getByRole("button", { name: "切换会话", exact: true }).click();
  await page.getByRole("listbox", { name: "项目列表" }).getByRole("option", { name: /项目收纳验收/ }).click();
  const group = page.getByRole("region", { name: "会话导航" });
  await expect(group).toBeVisible();
  const data = await page.evaluate(async () => ({ projects: await window.mozi!.agent.listProjects(), sessions: await window.mozi!.agent.listSessions() }));
  expect(data.projects.ok && data.sessions.ok && data.sessions.result.items[0].projectId === data.projects.result.items[0].id).toBe(true);
  await group.getByRole("button", { name: "＋ 新建会话", exact: true }).click();
  await expect(page.getByRole("dialog", { name: "切换会话", exact: true })).not.toBeVisible();
  await page.getByRole("button", { name: "切换会话", exact: true }).click();
  await expect(group.getByRole("option")).toHaveCount(2);
  await group.getByRole("button", { name: "删除项目", exact: true }).click();
  await page.getByRole("dialog", { name: "删除项目", exact: true }).getByRole("button", { name: "删除项目", exact: true }).click();
  await expect(page.getByRole("listbox", { name: "项目列表" }).getByRole("option", { name: /项目收纳验收/ })).toHaveCount(0);
  await expect(page.getByRole("listbox", { name: "匹配的会话" }).getByRole("option")).toHaveCount(2);
  const sessions = await page.evaluate(() => window.mozi!.agent.listSessions());
  expect(sessions.ok && sessions.result.items.every(s => s.projectId === null)).toBe(true);
});

test("two-pane keyboard navigation preserves selection, scopes search and does not hijack text cursors", async ({ desktop }) => {
  const { page } = desktop;
  await page.evaluate(async () => {
    await window.mozi!.agent.createProject({ projectId: "keys-a", name: "项目 Alpha" });
    await window.mozi!.agent.createProject({ projectId: "keys-b", name: "项目 Beta" });
    await window.mozi!.agent.createProject({ projectId: "keys-empty", name: "空项目" });
    await window.mozi!.agent.createSession({ clientOperationId: "keys-1", title: "Alpha first", projectId: "keys-a" });
    await window.mozi!.agent.createSession({ clientOperationId: "keys-2", title: "Alpha second", projectId: "keys-a" });
    await window.mozi!.agent.createSession({ clientOperationId: "keys-3", title: "Beta only", projectId: "keys-b" });
  });
  await page.getByRole("button", { name: "切换会话", exact: true }).click();
  const left = page.getByRole("listbox", { name: "项目列表" });
  const right = page.getByRole("listbox", { name: "匹配的会话" });
  const search = page.getByRole("combobox", { name: "搜索会话标题" });
  await expect(right).toHaveAttribute("data-active", "true");
  await expect(right).not.toBeFocused();
  await page.keyboard.press("Shift+F6");
  await expect(page.getByRole("textbox", { name: "消息内容" })).not.toBeFocused();
  await page.keyboard.press("ArrowLeft");
  await expect(left).toHaveAttribute("data-active", "true");
  await expect(left).not.toBeFocused();
  await page.keyboard.press("ArrowDown");
  await expect(left.getByRole("option", { name: /项目 Alpha/ })).toHaveAttribute("aria-selected", "true");
  await expect(right.getByRole("option")).toHaveCount(2);
  await page.keyboard.press("ArrowRight");
  await expect(right).toHaveAttribute("data-active", "true");
  await expect(right).not.toBeFocused();
  await page.keyboard.press("ArrowDown");
  const selectedTitle = (await right.locator('[aria-selected="true"]').textContent()) ?? "";
  await page.keyboard.press("ArrowLeft");
  await page.keyboard.press("ArrowDown");
  await expect(right.getByRole("option")).toHaveCount(1);
  await page.keyboard.press("ArrowUp");
  await page.keyboard.press("Enter");
  await expect(right).toHaveAttribute("data-active", "true");
  await expect(right).not.toBeFocused();
  await expect(right.locator('[aria-selected="true"]')).toHaveText(selectedTitle);
  await page.keyboard.press("Control+f");
  await expect(search).toBeFocused();
  await search.fill("Beta only");
  await expect(left.getByRole("option")).toHaveCount(1);
  await expect(right.getByRole("option", { name: /Beta only/ })).toBeVisible();
  await search.press("ArrowLeft");
  await expect(search).toBeFocused();
  expect(await search.evaluate(el => (el as HTMLInputElement).selectionStart)).toBe(8);
  await search.fill("");
  await expect(left.getByRole("option", { name: /项目 Alpha/ })).toHaveAttribute("aria-selected", "true");
  await expect(right.locator('[aria-selected="true"]')).toHaveText(selectedTitle);
  await search.fill("项目 Beta");
  await expect(right.getByRole("option", { name: /Beta only/ })).toBeVisible();
  await search.fill(">this-command-does-not-exist");
  await search.press("ArrowDown");
  const commands = page.getByRole("listbox", { name: "匹配的命令" });
  await expect(commands).not.toBeFocused();
  await page.keyboard.press("Enter");
  await expect(page.getByRole("dialog", { name: "切换会话", exact: true })).toBeVisible();
  await page.keyboard.press("Control+f");
  await search.fill("");
  await search.press("ArrowDown");
  await expect(right).toHaveAttribute("data-active", "true");
  await expect(right).not.toBeFocused();
  await page.keyboard.press("ArrowLeft");
  await left.getByRole("option", { name: /空项目/ }).click();
  await page.keyboard.press("ArrowRight");
  await expect(right).toHaveAttribute("data-active", "true");
  await expect(right).not.toBeFocused();
  await expect(right.getByRole("option")).toHaveCount(0);
  await expect(right.getByText("暂无历史会话")).toBeVisible();
  await page.keyboard.press("ArrowLeft");
  await left.getByRole("option", { name: /项目 Alpha/ }).click();
  await page.keyboard.press("ArrowRight");
  await page.keyboard.press("Enter");
  await expect(page.getByRole("dialog", { name: "切换会话", exact: true })).not.toBeVisible();
  await page.getByRole("button", { name: "切换会话", exact: true }).click();
  await expect(right).toHaveAttribute("data-active", "true");
  await expect(right).not.toBeFocused();
  await expect(left.getByRole("option", { name: /项目 Alpha/ })).toHaveAttribute("aria-selected", "true");
  await expect(right.locator('[aria-current="true"]')).toHaveAttribute("aria-selected", "true");
  await page.keyboard.press("Escape");
  await expect(page.getByRole("dialog", { name: "切换会话", exact: true })).not.toBeVisible();
  const chatInput = page.getByRole("textbox", { name: "消息内容" });
  await page.keyboard.press("Shift+F6");
  await expect(chatInput).toBeFocused();
  await page.keyboard.press("Shift+F6");
  await expect(chatInput).not.toBeFocused();
  await page.keyboard.press("F6");
  await expect(chatInput).toBeFocused();
});
